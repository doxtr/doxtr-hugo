"""doxtr-hugo — a Sphinx builder that emits Hugo-ready Markdown and assets.

The extension registers a ``hugo`` builder (``sphinx-build -b hugo``) that walks
the resolved doctree and writes one Markdown file per document plus co-located
assets, laid out as a buildable Hugo site. See the implementation guide for the
full contract.
"""

__version__ = "0.1.0"


def register_backend(backend, node_names, *, runner=None, node_extra_args=None):
    """Register a custom diagram backend (public consumer seam).

    Thin re-export of :func:`doxtr_hugo.diagrams.register_backend` so downstream
    extensions can register a :class:`~doxtr_hugo.diagrams.DiagramBackend`, map
    its doctree node class names, and optionally supply a custom subprocess
    ``runner`` and per-node ``node_extra_args`` hook — without importing a
    private module path. See that function for full parameter docs.
    """
    from .diagrams import register_backend as _register_backend

    return _register_backend(
        backend,
        node_names,
        runner=runner,
        node_extra_args=node_extra_args,
    )


def _exclude_overlay_from_sphinx(app, config):
    """Idempotently exclude the theme-overlay sidecar from Sphinx's doc scan.

    The overlay dir (``doxtr_hugo_theme_overlay_dir``, default ``.doxtr/hugo``)
    holds Hugo input that must not be parsed as reStructuredText or flagged as
    "not in any toctree". Add a glob for the dotted ``.doxtr`` namespace to
    ``exclude_patterns`` unless it is already covered, preserving any patterns
    the user configured.
    """
    overlay = getattr(config, "doxtr_hugo_theme_overlay_dir", "") or ""
    # Only auto-exclude a confdir-relative overlay (an absolute path points
    # outside the source tree and is never scanned by Sphinx anyway).
    import os as _os

    if not overlay or _os.path.isabs(overlay):
        return
    top = overlay.replace("\\", "/").split("/", 1)[0] or overlay
    patterns = list(getattr(config, "exclude_patterns", []) or [])
    glob = f"{top}/**"
    if top not in patterns and glob not in patterns:
        patterns.append(glob)
        config.exclude_patterns = patterns


def setup(app):
    """Register the Hugo builder and all ``doxtr_hugo_*`` config values.

    This is the entire integration surface of the extension: adding the builder
    makes ``sphinx-build -b hugo`` (and the ``make hugo`` target generated by
    ``sphinx-quickstart``) work, and registering the config values exposes the
    configuration surface documented in ``config_defaults.DEFAULT_CONFIG``.
    """
    from .builder import HugoBuilder
    from .config_defaults import DEFAULT_CONFIG

    app.add_builder(HugoBuilder)
    for name, default in DEFAULT_CONFIG.items():
        # "env" rebuild: a change to any of these values invalidates the
        # emitted output, so Sphinx should rebuild the environment.
        app.add_config_value(name, default, "env")

    # The theme-overlay sidecar (``.doxtr/hugo/`` by default) lives under the
    # source tree but is Hugo input, not Sphinx documents. Exclude it so Sphinx
    # neither parses its files nor warns that they are not in any toctree. Done
    # idempotently on ``config-inited`` so a user's ``exclude_patterns`` is
    # preserved.
    app.connect("config-inited", _exclude_overlay_from_sphinx)

    return {
        "version": __version__,
        "parallel_read_safe": True,
        "parallel_write_safe": True,
    }
